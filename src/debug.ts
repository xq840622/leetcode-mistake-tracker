import * as vscode from 'vscode';
import * as fs from 'fs';
import * as path from 'path';

/**
 * 通用调试驱动：importlabuladong 生成的题目文件 → 解析文件里的 @lcpr case 测试用例
 * → 反射找到 Solution 类与求解方法 → 按类型注解把 list 包装成 ListNode/TreeNode → 调用并打印结果。
 * 文件里的断点在调试器下正常生效（驱动就是原样 exec 该文件）。
 */
export const DRIVER_SOURCE = [
    '#!/usr/bin/env python3',
    '# leetcode-mistake-tracker 通用调试驱动（自动生成，勿手改）',
    'import ast',
    'import importlib.util',
    'import inspect',
    'import sys',
    'import time',
    'from pathlib import Path',
    '',
    'RESULTS = []  # 每个用例的结果（可视化录制阶段从这里读）',
    '',
    'solution_path = Path(sys.argv[1]).resolve()',
    "sys.path.insert(0, str(solution_path.parent.parent))  # editor 目录（common/node.py 所在层）",
    'only = int(sys.argv[2]) if len(sys.argv) > 2 else 0  # 回放指定 case：只跑第 N 个用例（0 = 全部）',
    '',
    "spec = importlib.util.spec_from_file_location('__lmt_solution__', str(solution_path))",
    'mod = importlib.util.module_from_spec(spec)',
    'try:',
    '    spec.loader.exec_module(mod)',
    'except (SyntaxError, IndentationError) as e:',
    "    sys.exit(f'❌ 题目文件本身有语法错误（第 {e.lineno} 行附近）：{e.msg}\\n   空壳题目先写上 class Solution: pass 再调试')",
    '',
    '',
    'def find_solution_class(root):',
    '    # 新版模板：模块顶层直接 class Solution；旧版：嵌在题目同名外层类里',
    "    for _, cls in inspect.getmembers(root, inspect.isclass):",
    "        if cls.__name__ == 'Solution' and cls.__module__ == mod.__name__:",
    '            return cls',
    "    for _, cls in inspect.getmembers(root, inspect.isclass):",
    '        if cls.__module__ == mod.__name__:',
    '            found = find_solution_class(cls)',
    '            if found is not None:',
    '                return found',
    '    return None',
    '',
    '',
    'Sol = find_solution_class(mod)',
    'if Sol is None:',
    "    sys.exit('❌ 没找到 Solution 类（新版模板在顶层，旧版嵌在题目同名类里）')",
    '',
    'method = next((n for n, f in inspect.getmembers(Sol, inspect.isfunction) if not n.startswith("_")), None)',
    'if method is None:',
    "    sys.exit('❌ Solution 里没有公开方法')",
    'params = [p for p in inspect.signature(getattr(Sol, method)).parameters.values()]',
    'if params and params[0].name == "self":',
    '    params = params[1:]',
    'print(f"▶ {solution_path.name} · Solution.{method}（{len(params)} 个参数）")',
    '',
    '',
    '# 解析 @lcpr case=start ... case=end 注释块，块内是含转义 \\n 的字面量行',
    'text = solution_path.read_text(encoding="utf-8")',
    'cases, cur = [], None',
    'for line in text.splitlines():',
    '    s = line.strip()',
    '    if s.startswith("# @lcpr case=start"):',
    '        cur = []',
    '    elif s.startswith("# @lcpr case=end"):',
    '        if cur is not None and cur:',
    '            cases.append("\\n".join(cur))',
    '        cur = None',
    '    elif cur is not None and s.startswith("#"):',
    '        cur.append(s.lstrip("#").strip())',
    '',
    'SEP = chr(92) + "n"  # 反斜杠+n，lcpr 的参数分隔转义',
    '',
    '',
    'def parse_case(raw):',
    '    values = []',
    '    for piece in raw.split(SEP):',
    '        piece = piece.strip()',
    '        if not piece or piece == SEP:',
    '            continue',
    '        piece = piece.replace("null", "None").replace("true", "True").replace("false", "False")',
    '        try:',
    '            values.append(ast.literal_eval(piece))',
    '        except Exception as e:',
    '            return None, f"参数 {piece!r} 解析失败: {e}"',
    '    return values, None',
    '',
    '',
    'def build_arg(value, ann):',
    '    if value is None:',
    '        return None',
    '    name = str(ann)',
    "    if 'ListNode' in name and isinstance(value, list):",
    '        from common.node import ListNode',
    '        return ListNode.create_head(value)',
    "    if 'TreeNode' in name and isinstance(value, list):",
    '        from common.node import TreeNode',
    '        return TreeNode.create_root(value)',
    '    return value',
    '',
    '',
    'def show(res):',
    '    if res is None:',
    '        return None',
    "    if hasattr(res, 'val') and hasattr(res, 'next'):  # ListNode → 数组",
    '        out, p = [], res',
    '        while p:',
    '            out.append(p.val)',
    '            p = p.next',
    '        return out',
    "    if hasattr(res, 'val') and hasattr(res, 'left'):  # TreeNode → 层序数组",
    '        out, queue = [], [res]',
    '        while queue:',
    '            n = queue.pop(0)',
    '            out.append(None if n is None else n.val)',
    '            if n is not None and (n.left is not None or n.right is not None):',
    '                queue.append(n.left)',
    '                queue.append(n.right)',
    '        while out and out[-1] is None:',
    '            out.pop()',
    '        return out',
    '    return res',
    '',
    '',
    'inst = Sol()',
    'if not cases:',
    '    print("⚠ 没解析到 @lcpr case 测试用例；在题目文件末尾补 case 注释块后重跑")',
    'for i, raw in enumerate(cases, 1):',
    '    if only and i != only:',
    '        continue',
    '    values, err = parse_case(raw)',
    '    if err:',
    '        print(f"case {i}: 跳过 —— {err}")',
    '        continue',
    '    if len(values) != len(params):',
    '        print(f"case {i}: 跳过 —— 参数个数 {len(values)} 与方法签名 {len(params)} 不符: {values}")',
    '        continue',
    '    args = [build_arg(v, p.annotation) for v, p in zip(values, params)]',
    '    t0 = time.perf_counter()',
    '    res = getattr(inst, method)(*args)',
    '    ms = (time.perf_counter() - t0) * 1000',
    "    RESULTS.append({'case': i, 'value': show(res), 'ms': round(ms, 2)})",
    '    print(f"case {i}: {show(res)!r}   ({ms:.2f} ms)")',
    'print("✅ 驱动执行完毕")',
    ''
].join('\n');

/** 把驱动写到扩展存储目录，返回文件路径（启动 debugpy 会话用） */
export function ensureDriver(ctx: vscode.ExtensionContext): string {
    const dir = ctx.globalStorageUri.fsPath;
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, 'debug_driver.py');
    fs.writeFileSync(file, DRIVER_SOURCE, 'utf8');
    return file;
}

/** RESULTS.append 所在行号（1-based）；可视化录制在此下断点读取全部用例结果 */
export function driverResultLine(): number {
    return DRIVER_SOURCE.split('\n').findIndex(l => l.includes('RESULTS.append')) + 1;
}

/** 驱动最后一行（print 完成提示）的行号：断在这里时 RESULTS 必然完整（append 行首断点读不到最后一条） */
export function driverDoneLine(): number {
    return DRIVER_SOURCE.split('\n').findIndex(l => l.includes('驱动执行完毕')) + 1;
}
